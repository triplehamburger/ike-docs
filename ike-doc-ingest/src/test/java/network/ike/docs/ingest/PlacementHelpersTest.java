package network.ike.docs.ingest;

import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;

/// The small pieces the build stage uses to place a record: registration text,
/// image references, the module list in a pom, and the git state of a folder.
class PlacementHelpersTest {

    @TempDir
    Path dir;

    @Test
    void fragmentOrder_isTheOrderOfTheAssemblyIncludesEachOnce() {
        String assembly = "= K1\n\ninclude::{topics}/topics/dex/b.adoc[leveloffset=+1]\n\n"
                + "include::{topics}/topics/dex/a.adoc[leveloffset=+1]\n\n"
                + "include::{topics}/topics/dex/b.adoc[leveloffset=+1]\n\ninclude::{topics}/other/c.adoc[]\n";
        assertThat(DexRegistration.fragmentOrder(assembly)).containsExactly("b.adoc", "a.adoc");
    }

    @Test
    void recordId_dropsTheDeXRecordPrefixOnly() {
        assertThat(DexRegistration.recordId("DeXRecord_K242783")).isEqualTo("K242783");
        assertThat(DexRegistration.recordId("FA3-D1")).isEqualTo("FA3-D1");
    }

    @Test
    void recordIdOf_readsAnIncludesFileNameAndNothingElse() {
        assertThat(DexRegistration.recordIdOf("_includes-K1.adoc")).isEqualTo("K1");
        assertThat(DexRegistration.recordIdOf("_includes-.adoc")).isNull();
        assertThat(DexRegistration.recordIdOf("k1-one.adoc")).isNull();
        assertThat(DexRegistration.includesFileName("K1")).isEqualTo("_includes-K1.adoc");
    }

    @Test
    void generatedFiles_matchTheShapeCheckedOnACleanDeXProject() {
        assertThat(DexRegistration.includesFile("K1", "= K1\n\ninclude::{topics}/topics/dex/a.adoc[leveloffset=+1]\n",
                List.of("b.adoc"))).isEqualTo(
                "// generated by idoc:ingest-build - do not edit\n= K1\n\n"
                        + "include::a.adoc[leveloffset=+1]\n\ninclude::b.adoc[leveloffset=+1]\n");
        assertThat(DexRegistration.indexFile("topics/dex", List.of("K1", "K2")))
                .startsWith("= DeX Records\n").contains(":imagesdir: images\n")
                .endsWith("== DeX Records\n\ninclude::topics/dex/_includes-K1.adoc[leveloffset=+2]\n\n"
                        + "include::topics/dex/_includes-K2.adoc[leveloffset=+2]\n");
        assertThat(DexRegistration.compendiumFile("topics/dex", List.of("K1")))
                .contains(":topics: {generated}/topics-asciidoc").contains(":imagesdir: {topics}/images")
                .contains("include::{topics}/topics/dex/_includes-K1.adoc[leveloffset=+2]")
                .endsWith("\n[index]\n== Index\n");
    }

    @Test
    void includesFile_keepsTheAssemblysOwnTextAndTitleAndItsStructure() {
        String assembly = "= SPECIAL 510(k) DECISION SUMMARY\n\n// REVIEW: picture\nimage::dex/K1/p.jpg[Pic]\n\n"
                + "== Section\n\nIntro words only the assembly holds.\n\n"
                + ". Study one\n+\ninclude::{topics}/topics/dex/s1.adoc[leveloffset=+1]\n";
        assertThat(DexRegistration.includesFile("K1", assembly, List.of())).isEqualTo(
                "// generated by idoc:ingest-build - do not edit\n= K1\n\nSPECIAL 510(k) DECISION SUMMARY\n\n"
                        + "// REVIEW: picture\nimage::dex/K1/p.jpg[Pic]\n\n== Section\n\n"
                        + "Intro words only the assembly holds.\n\n. Study one\n+\ninclude::s1.adoc[leveloffset=+1]\n");
    }

    @Test
    void includesFile_listsAFragmentTheAssemblyDoesNotIncludeLastAndSkipsARepeatedTitle() {
        assertThat(DexRegistration.includesFile("K1", "= K1\n", List.of("x.adoc", "y.adoc"))).isEqualTo(
                "// generated by idoc:ingest-build - do not edit\n= K1\n\n"
                        + "include::x.adoc[leveloffset=+1]\n\ninclude::y.adoc[leveloffset=+1]\n");
    }

    @Test
    void targets_listsLocalImagesOnceAndSkipsUrlsAttributesAndLocalFileUris() {
        String text = "image::images/a.png[A]\ntext image:b.png[B] more\nimage::images/a.png[again]\n"
                + "image::https://x.org/c.png[C]\nimage::{imagesdir}/d.png[D]\nimage::file:///e.png[E]\n"
                + "image::data:image/png;base64,AAAA[F]\n";
        assertThat(ImageReferences.targets(text)).containsExactly("images/a.png", "b.png");
    }

    @Test
    void rewrite_changesLocalTargetsAndKeepsEverythingElse() {
        String text = "image::images/a.png[\"A, a\",width=10]\nimage::https://x.org/c.png[C]\n";
        assertThat(ImageReferences.rewrite(text, t -> "dex/K1/" + ImageReferences.insideImages(t)))
                .isEqualTo("image::dex/K1/a.png[\"A, a\",width=10]\nimage::https://x.org/c.png[C]\n");
        assertThat(ImageReferences.rewrite(text, t -> null)).isEqualTo(text);
    }

    @Test
    void insideImages_stripsOnlyALeadingImagesFolder() {
        assertThat(ImageReferences.insideImages("images/a.png")).isEqualTo("a.png");
        assertThat(ImageReferences.insideImages("images\\sub\\a.png")).isEqualTo("sub/a.png");
        assertThat(ImageReferences.insideImages("a.png")).isEqualTo("a.png");
        assertThat(ImageReferences.insideImages("x/images/a.png")).isEqualTo("x/images/a.png");
    }

    private static final String POM = "<project>\r\n    <subprojects>\r\n        <subproject>a</subproject>\r\n"
            + "    </subprojects>\r\n</project>\r\n";

    @Test
    void add_insertsBeforeTheClosingTagKeepsTheIndentAndTheLineEndings() {
        PomModules.Result result = PomModules.add(POM, "b");
        assertThat(result.changed()).isTrue();
        assertThat(result.element()).isEqualTo("subprojects");
        assertThat(result.text()).isEqualTo("<project>\r\n    <subprojects>\r\n        <subproject>a</subproject>\r\n"
                + "        <subproject>b</subproject>\r\n    </subprojects>\r\n</project>\r\n");
    }

    @Test
    void add_doesNothingWhenTheModuleIsListed() {
        PomModules.Result result = PomModules.add(POM, "a");
        assertThat(result.changed()).isFalse();
        assertThat(result.text()).isEqualTo(POM);
    }

    @Test
    void add_ignoresCommentedOutElements() {
        String pom = "<project>\n<!-- <subproject>b</subproject>\n</subprojects> -->\n<subprojects>\n"
                + "    <subproject>a</subproject>\n</subprojects>\n</project>\n";
        PomModules.Result result = PomModules.add(pom, "b");
        assertThat(result.changed()).isTrue();
        assertThat(result.text()).endsWith("    <subproject>a</subproject>\n    <subproject>b</subproject>\n"
                + "</subprojects>\n</project>\n");
        assertThat(result.text()).startsWith("<project>\n<!-- <subproject>b</subproject>\n</subprojects> -->\n");
    }

    @Test
    void add_fallsBackToModulesAndReportsAPomWithNeither() {
        PomModules.Result modules = PomModules.add("<project><modules>\n</modules></project>", "m");
        assertThat(modules.element()).isEqualTo("modules");
        assertThat(modules.text()).contains("<module>m</module>");
        PomModules.Result none = PomModules.add("<project/>", "m");
        assertThat(none.element()).isNull();
        assertThat(none.changed()).isFalse();
    }

    @Test
    void manifestOpen_continuesFromAMatchingManifestAndStartsFreshOtherwise() throws IOException {
        Manifest.Source source = new Manifest.Source("a.pdf", "aa", SourceKind.PDF);
        Path file = dir.resolve("ingest.yaml");
        assertThat(ManifestRun.open(file, source).stages()).isEmpty();

        Manifest done = Manifest.of(source).withStage("convert", new Manifest.Stage(Manifest.Status.OK,
                java.util.Map.of(), java.util.Map.of(), null, java.util.Map.of(), List.of(), List.of()));
        done.write(file);
        assertThat(ManifestRun.open(file, source).stages()).containsKey("convert");
        assertThat(ManifestRun.open(file, new Manifest.Source("a.pdf", "bb", SourceKind.PDF)).stages()).isEmpty();

        Files.writeString(file, "not: [valid");
        assertThat(ManifestRun.open(file, source).stages()).isEmpty();
    }

    @Test
    void hashTree_andHashFiles_keyFilesByPathRelativeToTheBase() throws IOException {
        Files.createDirectories(dir.resolve("out/sub"));
        Files.writeString(dir.resolve("out/a.txt"), "a");
        Files.writeString(dir.resolve("out/sub/b.txt"), "b");
        assertThat(ManifestRun.hashTree(dir, dir.resolve("out"))).containsOnlyKeys("out/a.txt", "out/sub/b.txt")
                .containsEntry("out/a.txt", IngestHash.sha256Hex("a"));
        assertThat(ManifestRun.hashTree(dir, dir.resolve("missing"))).isEmpty();
        assertThat(ManifestRun.hashFiles(dir, List.of(dir.resolve("out/a.txt"), dir.resolve("out/none.txt"))))
                .containsOnlyKeys("out/a.txt");
    }

    private static boolean gitAvailable() {
        try {
            return new ProcessBuilder("git", "--version").redirectErrorStream(true).start().waitFor() == 0;
        } catch (IOException | InterruptedException e) {
            return false;
        }
    }

    @Test
    void dirtyPaths_isEmptyForANonRepositoryAndListsChangesInARepository() throws Exception {
        Assumptions.assumeTrue(gitAvailable(), "git is needed");
        Path plain = Files.createDirectories(dir.resolve("plain"));
        assertThat(GitState.dirtyPaths(plain)).isEqualTo(Optional.empty());

        Path repo = Files.createDirectories(dir.resolve("repo"));
        new ProcessBuilder("git", "init", "-q").directory(repo.toFile()).redirectErrorStream(true).start().waitFor();
        assertThat(GitState.dirtyPaths(repo)).contains(List.of());
        Files.writeString(repo.resolve("new.txt"), "x");
        assertThat(GitState.dirtyPaths(repo)).hasValueSatisfying(paths -> assertThat(paths).containsExactly("new.txt"));
    }
}
