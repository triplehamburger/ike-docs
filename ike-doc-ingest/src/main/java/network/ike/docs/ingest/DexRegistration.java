package network.ike.docs.ingest;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/// The text of the files that register ingested records in a DeX project, so
/// no person edits a hand-owned file to make a record appear.
///
/// For each record `K` the build stage writes `_includes-K.adoc` beside the
/// topics, one include per fragment in source order. From the records found
/// there it writes the sibling `index-dex-records.adoc`, which the topics build
/// renders next to the reference index, and the `DeXRecords` compendium
/// source. All three are rewritten from the fragments on every run, so they
/// cannot drift from them. Each starts with {@link #GENERATED} so a reader
/// knows not to edit it.
public final class DexRegistration {

    /// The comment that opens every generated file.
    public static final String GENERATED = "// generated by idoc:ingest-build - do not edit";

    /// The prefix of the file that lists one record's fragments.
    public static final String INCLUDES_PREFIX = "_includes-";

    /// The file name of the topics-module index of ingested records.
    public static final String INDEX_FILE = "index-dex-records.adoc";

    /// The assembly module that holds every ingested record.
    public static final String COMPENDIUM_MODULE = "DeXRecords";

    private static final Pattern ASSEMBLY_INCLUDE = Pattern.compile(
            "^include::\\{topics}/topics/dex/([^\\[\\s/]+\\.adoc)\\[", Pattern.MULTILINE);

    private DexRegistration() {
    }

    /// The fragment files an assembly includes, in the order it includes them,
    /// each once.
    ///
    /// @param assembly the assembly text written by the split stage
    /// @return the fragment file names, for example `k1-review-summary.adoc`
    public static List<String> fragmentOrder(String assembly) {
        LinkedHashSet<String> files = new LinkedHashSet<>();
        Matcher m = ASSEMBLY_INCLUDE.matcher(assembly);
        while (m.find()) {
            files.add(m.group(1));
        }
        return new ArrayList<>(files);
    }

    /// The record id for an assembly file name: the name without `DeXRecord_`.
    ///
    /// @param assemblyBase the assembly file name without `.adoc`
    /// @return the record id
    public static String recordId(String assemblyBase) {
        return assemblyBase.startsWith("DeXRecord_") ? assemblyBase.substring("DeXRecord_".length())
                : assemblyBase;
    }

    /// The file name of the includes file of a record.
    ///
    /// @param recordId the record id
    /// @return `_includes-ID.adoc`
    public static String includesFileName(String recordId) {
        return INCLUDES_PREFIX + recordId + ".adoc";
    }

    /// The record id an includes file name stands for, or null when the name
    /// is not an includes file name.
    ///
    /// @param fileName a file name
    /// @return the record id, or null
    public static String recordIdOf(String fileName) {
        if (fileName.startsWith(INCLUDES_PREFIX) && fileName.endsWith(".adoc")
                && fileName.length() > INCLUDES_PREFIX.length() + ".adoc".length()) {
            return fileName.substring(INCLUDES_PREFIX.length(), fileName.length() - ".adoc".length());
        }
        return null;
    }

    /// The includes file of one record: its fragments at one level down.
    ///
    /// @param recordId the record id, used as the title
    /// @param fragments the fragment file names, in source order
    /// @return the file text
    public static String includesFile(String recordId, List<String> fragments) {
        StringBuilder text = new StringBuilder(GENERATED).append("\n= ").append(recordId).append('\n');
        for (String fragment : fragments) {
            text.append("\ninclude::").append(fragment).append("[leveloffset=+1]\n");
        }
        return text.toString();
    }

    /// The topics-module index of ingested records, `index-dex-records.adoc`.
    ///
    /// @param topicsDirFromRoot the folder holding the includes files, relative to the topics
    ///                          AsciiDoc root, with forward slashes (`topics/dex`)
    /// @param recordIds         the record ids, in the order to list them
    /// @return the file text
    public static String indexFile(String topicsDirFromRoot, List<String> recordIds) {
        StringBuilder text = new StringBuilder("= DeX Records\n:doctype: book\n:toc: left\n:toclevels: 3\n"
                + ":icons: font\n:imagesdir: images\n\n" + GENERATED + "\n== DeX Records\n");
        for (String id : recordIds) {
            text.append("\ninclude::").append(topicsDirFromRoot).append('/').append(includesFileName(id))
                    .append("[leveloffset=+2]\n");
        }
        return text.toString();
    }

    /// The source of the `DeXRecords` compendium: every record, then the term index.
    ///
    /// @param topicsDirFromRoot the folder holding the includes files, relative to the topics
    ///                          AsciiDoc root, with forward slashes (`topics/dex`)
    /// @param recordIds         the record ids, in the order to list them
    /// @return the file text
    public static String compendiumFile(String topicsDirFromRoot, List<String> recordIds) {
        StringBuilder text = new StringBuilder("= DeX Records\n:doctype: book\n:toc: left\n:toclevels: 3\n"
                + ":sectnums:\n:sectnumlevels: 3\n:source-highlighter: rouge\n:icons: font\n:author: IKE Network\n"
                + ":topics: {generated}/topics-asciidoc\n:imagesdir: {topics}/images\n\n" + GENERATED
                + "\n== DeX Records\n");
        for (String id : recordIds) {
            text.append("\ninclude::{topics}/").append(topicsDirFromRoot).append('/')
                    .append(includesFileName(id)).append("[leveloffset=+2]\n");
        }
        return text.append("\n[index]\n== Index\n").toString();
    }
}
